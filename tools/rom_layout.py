#!/usr/bin/env python3
"""Emit model tensors, LUTs and the word table as RGBDS source for a chosen ROM layout.

naive:      each tensor is a floating ROMX section; the linker decides, tensors may land in several banks.
bank_aware: all tensors in one fixed bank in consumption order, each row starting at a known pointer.
biased weights (--biased) store w+128 so a table-based MAC can index without sign logic.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "tools")]
from export_weights import from_blob, TENSORS
from reference import fixed_point as fp
from training import dialogue as ds
from reference import conversation as cv

BANK_AWARE_BANK = 2
UI_BANK = 1
ORDER = ("tok", "pos", "w_q", "w_k", "w_v", "w_o", "w_f1", "w_f2", "w_b", "w_out")
LABEL = {"tok": "Tok", "pos": "Pos", "w_q": "Q", "w_k": "K", "w_v": "V", "w_o": "O", "w_f1": "F1", "w_f2": "F2", "w_b": "B", "w_out": "Out"}
TOK_ROWS_PER_BANK = 512


def _db(vals) -> str:
    rows = []
    vals = list(vals)
    for i in range(0, len(vals), 32):
        rows.append("    db " + ",".join(f"${v & 0xFF:02X}" for v in vals[i:i + 32]))
    return "\n".join(rows)


def luts() -> str:
    return "\n".join(['SECTION "luts", ROM0, ALIGN[8]', "ExpLut::", _db(fp.EXP_LUT), "NormLut::", _db(fp.NORM_LUT),
                      'SECTION "recip_lut", ROM0, ALIGN[8]', "RecipLut::", _db(fp.RECIP_LUT), ""])


def qsq_table() -> str:
    """Quarter squares q(n)=floor(n^2/4). Pages: [q(i-256) lo, q(i) lo, q(i-256) hi, q(i) hi] for i in 0..255."""
    neg = [((i - 256) ** 2) // 4 for i in range(256)]
    pos = [(i ** 2) // 4 for i in range(256)]
    return "\n".join(['SECTION "qsq", ROM0, ALIGN[8]', "QTab::", _db(v & 255 for v in neg), _db(v & 255 for v in pos),
                      _db(v >> 8 for v in neg), _db(v >> 8 for v in pos), ""])


def nibble_table() -> str:
    """Products |a|*n for |a| in 0..127, n in 0..15: 2 KiB low bytes then 2 KiB high bytes."""
    vals = [a * n for a in range(128) for n in range(16)]
    return "\n".join(['SECTION "nib", ROM0, ALIGN[8]', "NibTab::", _db(v & 255 for v in vals), _db(v >> 8 for v in vals), ""])


def words() -> str:
    """Display strings for every generatable id, in the UI bank. Emotions, EOS and slots print nothing from this table."""
    out = [f'SECTION "words", ROMX, BANK[{UI_BANK}]', "WordPtrs::"]
    gen = ds.VOCAB[ds.FIRST_GEN:]
    out += [f"    dw Word{i}" for i in range(len(gen))]
    for i, w in enumerate(gen):
        text = "" if w.startswith("<") else w.upper()
        out.append(f'Word{i}: db "{text}", 0')
    return "\n".join(out) + "\n"


def weights(m, layout: str, biased: bool) -> str:
    """The token table is pinned to whole banks. bank_aware then fills banks in consumption order, keeping each tensor whole."""
    out = ["; AUTOGENERATED by tools/rom_layout.py"]
    table = ['SECTION "tensor_table", ROM0']
    bank, used = BANK_AWARE_BANK, 0
    for name in ORDER:
        t = getattr(m, name)
        shift = 4 if name in ("tok", "pos") else getattr(m, "s_" + name[2:])
        lab = LABEL[name]
        if name == "tok":
            for start in range(0, len(t), TOK_ROWS_PER_BANK):
                out.append(f'SECTION "w_tok{start}", ROMX[$4000], BANK[{bank}]')
                if start == 0:
                    out.append("DataTok::")
                for row in t[start:start + TOK_ROWS_PER_BANK]:
                    out.append(_db(row))
                used = len(t[start:start + TOK_ROWS_PER_BANK]) * len(t[0])
                if used == 0x4000:
                    bank, used = bank + 1, 0
                elif start + TOK_ROWS_PER_BANK < len(t):
                    bank, used = bank + 1, 0
            if layout == "naive":
                bank, used = bank + 1, 0
        else:
            if layout == "naive":
                out.append(f'SECTION "w_{name}", ROMX')
            else:
                size = len(t) * len(t[0])
                if used + size > 0x4000:
                    bank, used = bank + 1, 0
                used += size
                out.append(f'SECTION "w_{name}", ROMX, BANK[{bank}]')
            out.append(f"Data{lab}::")
            for row in t:
                out.append(_db((v + 128) if biased and name.startswith("w_") else v for v in row))
        table.append(f"T{lab}:: db BANK(Data{lab})\n    dw Data{lab}\n    db {len(t) & 255}, {len(t[0])}, {shift}")
    return "\n".join(out + table) + "\n"


def parser_tables(m) -> str:
    """Word records for src/parser.asm: 8 padded characters, cue class, topic, flags. Generated from reference/conversation.py."""
    cue_index = {c: i + 1 for i, c in enumerate(cv.PRIORITY)}
    words = sorted(set(cv.CUES) | set(cv.TOPIC_OF) | set(cv.STOP_WORDS) | set(cv.NEGATIONS) | set(cv.QUESTION_WORDS))
    out = [f'SECTION "parser_tables", ROMX, BANK[{UI_BANK}]', "ParserWords::"]
    for w in words:
        flags = (1 if w in cv.STOP_WORDS else 0) | (2 if w in cv.NEGATIONS else 0) | (4 if w in cv.QUESTION_WORDS else 0)
        topic = cv.TOPICS.index(cv.TOPIC_OF[w]) if w in cv.TOPIC_OF else 0
        cue = cue_index.get(cv.CUES.get(w, ""), 0)
        chars = ",".join(str(ord(c)) for c in w.ljust(8, "\0"))
        out.append(f"    db {chars}, {cue}, {topic}, {flags}")
    out += [f"ParserWordsEnd::", "CueIntent::", "    db 255," + ",".join(str(cv.INTENTS.index(c)) for c in cv.PRIORITY)]
    out += ["IntentEffects::"] + [f"    db {cv.EFFECTS[i][0] & 255}, {cv.EFFECTS[i][1] & 255}, {cv.EFFECTS[i][2] & 255}" for i in cv.INTENTS]
    out += ["ActionIntent::", "    db " + ",".join(str(cv.INTENTS.index(i)) for i in cv.ACTION_INTENT)]
    moods = ["SMUG", "AMUSED", "ANGRY", "WARY", "BORED", "DYING"]
    out += ["MoodNames::"] + [f"    dw Mood{i}" for i in range(len(moods))] + [f'Mood{i}: db "{n}", 0' for i, n in enumerate(moods)]
    out += ["RelationNames::"] + [f"    dw Rel{i}" for i in range(len(cv.RELATIONS))] + [f'Rel{i}: db "{n}", 0' for i, n in enumerate(cv.RELATIONS)]
    labels = list(cv.ACTIONS) + ["TYPE"]
    out += ["ActionNames::"] + [f"    dw Act{i}" for i in range(len(labels))] + [f'Act{i}: db "{n}", 0' for i, n in enumerate(labels)]
    out.append(f'StrModelParams:: db "{m.params} PARAMS", 0')
    return "\n".join(out) + "\n"


