#!/usr/bin/env python3
"""Emit model tensors, LUTs and the word table as RGBDS source for a chosen ROM layout.

naive:      each tensor is a floating ROMX section; the linker decides, tensors may land in several banks.
bank_aware: all tensors in one fixed bank in consumption order, each row starting at a known pointer.
biased weights (--biased) store w+128 so a table-based MAC can index without sign logic.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "tools")]
from export_weights import from_blob, TENSORS
from reference import fixed_point as fp
from training import dataset as ds
from reference import story as st

BANK_AWARE_BANK = 2
ORDER = ("tok", "pos", "w_q", "w_k", "w_v", "w_o", "w_f1", "w_f2", "w_out")
LABEL = {"tok": "Tok", "pos": "Pos", "w_q": "Q", "w_k": "K", "w_v": "V", "w_o": "O", "w_f1": "F1", "w_f2": "F2", "w_out": "Out"}


def _db(vals) -> str:
    rows = []
    vals = list(vals)
    for i in range(0, len(vals), 32):
        rows.append("    db " + ",".join(f"${v & 0xFF:02X}" for v in vals[i:i + 32]))
    return "\n".join(rows)


def luts() -> str:
    return "\n".join(['SECTION "luts", ROM0, ALIGN[8]', "ExpLut::", _db(fp.EXP_LUT), "NormLut::", _db(fp.NORM_LUT),
                      'SECTION "recip_lut", ROM0, ALIGN[8]', "RecipLut::", _db(fp.RECIP_LUT), ""])


def qsq_table() -> str:
    """Quarter squares q(n)=floor(n^2/4). Pages: [q(i-256) lo, q(i) lo, q(i-256) hi, q(i) hi] for i in 0..255."""
    neg = [((i - 256) ** 2) // 4 for i in range(256)]
    pos = [(i ** 2) // 4 for i in range(256)]
    return "\n".join(['SECTION "qsq", ROM0, ALIGN[8]', "QTab::", _db(v & 255 for v in neg), _db(v & 255 for v in pos),
                      _db(v >> 8 for v in neg), _db(v >> 8 for v in pos), ""])


def nibble_table() -> str:
    """Products |a|*n for |a| in 0..127, n in 0..15: 2 KiB low bytes then 2 KiB high bytes."""
    vals = [a * n for a in range(128) for n in range(16)]
    return "\n".join(['SECTION "nib", ROM0, ALIGN[8]', "NibTab::", _db(v & 255 for v in vals), _db(v >> 8 for v in vals), ""])


def words() -> str:
    out = ['SECTION "words", ROM0', "WordPtrs::"]
    gen = ds.VOCAB[ds.FIRST_GEN:]
    out += [f"    dw Word{i}" for i in range(len(gen))]
    for i, w in enumerate(gen):
        text = "" if w == "<EOS>" else w.lower()  # the first word of an event is capitalized at draw time
        out.append(f'Word{i}: db "{text}", 0')
    return "\n".join(out) + "\n"


def weights(m, layout: str, biased: bool) -> str:
    """bank_aware: fill banks in consumption order, keeping every tensor whole, so hot loops never cross a bank."""
    out = ["; AUTOGENERATED by tools/rom_layout.py"]
    table = ['SECTION "tensor_table", ROM0']
    bank, used = BANK_AWARE_BANK, 0
    for name in ORDER:
        t = getattr(m, name)
        shift = 4 if name in ("tok", "pos") else getattr(m, "s_" + name[2:])
        lab = LABEL[name]
        if layout == "naive":
            out.append(f'SECTION "w_{name}", ROMX')
        else:
            size = len(t) * len(t[0])
            if used + size > 0x4000:
                bank, used = bank + 1, 0
            used += size
            out.append(f'SECTION "w_{name}", ROMX, BANK[{bank}]')
        out.append(f"Data{lab}::")
        for row in t:
            out.append(_db((v + 128) if biased and name.startswith("w_") else v for v in row))
        table.append(f"T{lab}:: db BANK(Data{lab})\n    dw Data{lab}\n    db {len(t)}, {len(t[0])}, {shift}")
    return "\n".join(out + table) + "\n"


def _asm_string(text: str) -> str:
    return 'db "' + text + '", 0'


def story_tables(m) -> str:
    """Scene and choice records for src/game.asm. Scene: title, art, act, count, first choice, ending index.
    Choice: label, requires, forbids, sets, clears, wounds, next, beat token."""
    index = {s.id: i for i, s in enumerate(st.SCENES)}
    endings = list(st.ENDING_NAMES)
    out = ['SECTION "story_tables", ROM0', "StoryScenes::"]
    first = 0
    strings, choices = [], []
    for i, s in enumerate(st.SCENES):
        ending = endings.index(s.id) if s.ending else 255
        out += [f"    dw SceneTitle{i}", f"    db {s.art}, {st.ACTS.get(s.id, 3)}, {len(s.choices)}, {first}, {ending}"]
        strings.append(f"SceneTitle{i}: {_asm_string(s.title)}")
        for c in s.choices:
            n = len(choices)
            choices += [f"    dw ChoiceLabel{n}", f"    db {c.requires}, {c.forbids}, {c.sets}, {c.clears}, {c.wounds}, {index[c.next]}, {ds.STOI['<B_' + c.beat + '>']}"]
            strings.append(f"ChoiceLabel{n}: {_asm_string(c.label)}")
        first += len(s.choices)
    assert first == sum(len(s.choices) for s in st.SCENES) and first < 256
    flags = [ds.STOI.get(f"<F_{f}>", 0) for f in range(32)]
    params = sum(len(getattr(m, f)) * len(getattr(m, f)[0]) for f in ORDER)
    out += ["StoryChoices::", *choices, "FlagTokens::", _db(flags), "EndingNames::"]
    out += [f"    dw EndingName{i}" for i in range(len(endings))]
    out += [f"EndingName{i}: {_asm_string(st.ENDING_NAMES[e])}" for i, e in enumerate(endings)]
    out += strings + [f"StrModelParams:: {_asm_string(f'Model: {params} params')}"]
    return "\n".join(out) + "\n"


def constants(m) -> str:
    index = {s.id: i for i, s in enumerate(st.SCENES)}
    return "\n".join([
        f"DEF PROMPT_LEN EQU {ds.PROMPT_LEN}", f"DEF SCENE_START EQU {index[st.START]}", f"DEF SCENE_DEATH EQU {index[st.DEATH_SCENE]}",
        f"DEF MAX_WOUNDS EQU {st.MAX_WOUNDS}", f"DEF MAX_CHOICES EQU 4", f"DEF NUM_ENDINGS EQU {len(st.ENDING_NAMES)}",
        f"DEF TOK_FATE0 EQU {ds.STOI['<LIVE>']}",
        f"DEF FLAG_LAMP EQU {st.LAMP}", f"DEF FLAG_KEY EQU {st.KEY}", f"DEF FLAG_FRIEND EQU {st.FRIEND}", f"DEF FLAG_SWORD EQU {st.SWORD}", f"DEF FLAG_CURSED EQU {st.CURSED}",
        "; AUTOGENERATED model geometry",
        f"DEF MODEL_D EQU {m.d}", f"DEF MODEL_HEADS EQU {m.heads}", f"DEF MODEL_HEAD_DIM EQU {m.head_dim}",
        f"DEF MODEL_CTX EQU {m.ctx}", f"DEF MODEL_FFN EQU {len(m.w_f1)}", f"DEF MODEL_VOCAB EQU {len(m.w_out)}",
        f"DEF TOK_EOS EQU {m.eos}", f"DEF TOK_FIRST_GEN EQU {m.first_gen}", f"DEF SAMPLE_MARGIN EQU {m.sample_margin}",
        f"DEF SHIFT_Q EQU {m.s_q}", f"DEF SHIFT_K EQU {m.s_k}", f"DEF SHIFT_V EQU {m.s_v}", f"DEF SHIFT_O EQU {m.s_o}",
        f"DEF SHIFT_F1 EQU {m.s_f1}", f"DEF SHIFT_F2 EQU {m.s_f2}", f"DEF SHIFT_OUT EQU {m.s_out}",
        f"DEF ATTN_SHIFT EQU {fp.ATTN_SHIFT}", f"DEF LOGIT_SHIFT EQU {fp.LOGIT_SHIFT}", f"DEF W_SHIFT EQU {fp.W_SHIFT}",
        f"DEF SAMPLE_CANDS EQU {fp.SAMPLE_CANDIDATES}", "",
    ])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--blob", default=str(ROOT / "generated" / "model.bin"))
    ap.add_argument("--layout", default="naive", choices=["naive", "bank_aware"])
    ap.add_argument("--biased", action="store_true")
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--tables", nargs="*", default=[])
    a = ap.parse_args()
    m = from_blob(Path(a.blob).read_bytes())
    d = Path(a.outdir)
    d.mkdir(parents=True, exist_ok=True)
    (d / "weights.asm").write_text(weights(m, a.layout, a.biased))
    extra = ("qsq_table" in a.tables and qsq_table() or "") + ("nibble" in a.tables and nibble_table() or "")
    (d / "luts.asm").write_text(luts() + words() + extra + story_tables(m))
    (d / "model_constants.inc").write_text(constants(m))


if __name__ == "__main__":
    main()
