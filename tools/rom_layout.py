#!/usr/bin/env python3
"""Emit model tensors, LUTs and the word table as RGBDS source for a chosen ROM layout.

naive:      each tensor is a floating ROMX section; the linker decides, tensors may land in several banks.
bank_aware: all tensors in one fixed bank in consumption order, each row starting at a known pointer.
biased weights (--biased) store w+128 so a table-based MAC can index without sign logic.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "tools")]
from export_weights import from_blob, TENSORS
from reference import fixed_point as fp
from training import dataset as ds

BANK_AWARE_BANK = 2
ORDER = ("tok", "pos", "w_q", "w_k", "w_v", "w_o", "w_f1", "w_f2", "w_out")
LABEL = {"tok": "Tok", "pos": "Pos", "w_q": "Q", "w_k": "K", "w_v": "V", "w_o": "O", "w_f1": "F1", "w_f2": "F2", "w_out": "Out"}


def _db(vals) -> str:
    rows = []
    vals = list(vals)
    for i in range(0, len(vals), 32):
        rows.append("    db " + ",".join(f"${v & 0xFF:02X}" for v in vals[i:i + 32]))
    return "\n".join(rows)


def luts() -> str:
    return "\n".join(['SECTION "luts", ROM0, ALIGN[8]', "ExpLut::", _db(fp.EXP_LUT), "NormLut::", _db(fp.NORM_LUT),
                      'SECTION "recip_lut", ROM0, ALIGN[8]', "RecipLut::", _db(fp.RECIP_LUT), ""])


def words() -> str:
    out = ['SECTION "words", ROM0', "WordPtrs::"]
    gen = ds.VOCAB[ds.FIRST_GEN:]
    out += [f"    dw Word{i}" for i in range(len(gen))]
    for i, w in enumerate(gen):
        text = "" if w == "<EOS>" else w
        out.append(f'Word{i}: db "{text}", 0')
    return "\n".join(out) + "\n"


def weights(m, layout: str, biased: bool) -> str:
    out = ["; AUTOGENERATED by tools/rom_layout.py"]
    table = ['SECTION "tensor_table", ROM0']
    if layout == "bank_aware":
        out.append(f'SECTION "weights", ROMX, BANK[{BANK_AWARE_BANK}]')
    for name in ORDER:
        t = getattr(m, name)
        shift = 4 if name in ("tok", "pos") else getattr(m, "s_" + name[2:])
        lab = LABEL[name]
        if layout == "naive":
            out.append(f'SECTION "w_{name}", ROMX')
        out.append(f"Data{lab}::")
        for row in t:
            out.append(_db((v + 128) if biased else v for v in row))
        table.append(f"T{lab}:: db BANK(Data{lab})\n    dw Data{lab}\n    db {len(t)}, {len(t[0])}, {shift}")
    return "\n".join(out + table) + "\n"


def constants(m) -> str:
    return "\n".join([
        "; AUTOGENERATED model geometry",
        f"DEF MODEL_D EQU {m.d}", f"DEF MODEL_HEADS EQU {m.heads}", f"DEF MODEL_HEAD_DIM EQU {m.head_dim}",
        f"DEF MODEL_CTX EQU {m.ctx}", f"DEF MODEL_FFN EQU {len(m.w_f1)}", f"DEF MODEL_VOCAB EQU {len(m.w_out)}",
        f"DEF TOK_EOS EQU {m.eos}", f"DEF TOK_FIRST_GEN EQU {m.first_gen}", f"DEF SAMPLE_MARGIN EQU {m.sample_margin}",
        f"DEF SHIFT_Q EQU {m.s_q}", f"DEF SHIFT_K EQU {m.s_k}", f"DEF SHIFT_V EQU {m.s_v}", f"DEF SHIFT_O EQU {m.s_o}",
        f"DEF SHIFT_F1 EQU {m.s_f1}", f"DEF SHIFT_F2 EQU {m.s_f2}", f"DEF SHIFT_OUT EQU {m.s_out}",
        f"DEF ATTN_SHIFT EQU {fp.ATTN_SHIFT}", f"DEF LOGIT_SHIFT EQU {fp.LOGIT_SHIFT}", f"DEF W_SHIFT EQU {fp.W_SHIFT}",
        f"DEF SAMPLE_CANDS EQU {fp.SAMPLE_CANDIDATES}", "",
    ])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--blob", default=str(ROOT / "generated" / "model.bin"))
    ap.add_argument("--layout", default="naive", choices=["naive", "bank_aware"])
    ap.add_argument("--biased", action="store_true")
    ap.add_argument("--outdir", required=True)
    a = ap.parse_args()
    m = from_blob(Path(a.blob).read_bytes())
    d = Path(a.outdir)
    d.mkdir(parents=True, exist_ok=True)
    (d / "weights.asm").write_text(weights(m, a.layout, a.biased))
    (d / "luts.asm").write_text(luts() + words())
    (d / "model_constants.inc").write_text(constants(m))


if __name__ == "__main__":
    main()
